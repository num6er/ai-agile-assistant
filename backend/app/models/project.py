"""项目模型"""
from datetime import datetime
from ..extensions import db


class Project(db.Model):
    __tablename__ = "projects"

    id = db.Column(db.Integer, primary_key=True)
    name = db.Column(db.String(128), nullable=False)
    description = db.Column(db.Text)
    created_at = db.Column(db.DateTime, default=datetime.utcnow)
    updated_at = db.Column(db.DateTime, default=datetime.utcnow, onupdate=datetime.utcnow)

    # 关系
    requirements = db.relationship("Requirement", backref="project", cascade="all, delete-orphan")
    stories = db.relationship("UserStory", backref="project", cascade="all, delete-orphan")
    tasks = db.relationship("Task", backref="project", cascade="all, delete-orphan")
    members = db.relationship("Member", backref="project", cascade="all, delete-orphan")

    def to_dict(self):
        return {
            "id": self.id,
            "name": self.name,
            "description": self.description,
            "created_at": self.created_at.isoformat() if self.created_at else None,
            "updated_at": self.updated_at.isoformat() if self.updated_at else None,
        }
